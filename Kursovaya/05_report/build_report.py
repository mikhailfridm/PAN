# --- 3. Вывод соотношений для элементарных траекторий ---
h1("3. Вывод соотношений для расхода топлива и времени полета "
   "на элементарных участках траектории")

para("Внутри каждой элементарной подобласти сетки (V,H) движение ЛА из "
     "узла (Vi,Hj) возможно по одной из трех элементарных траекторий.")

h2("3.1. «Разгон» (H = const, Θ = 0)")
para("Высота полета не меняется, угол наклона траектории Θ=0, подъемная сила "
     "уравновешивает вес: Y=m·g. Из первого уравнения движения:")
mono("    m(dV/dt) = P - X   =>   Δt = m·(V2-V1) / (P-X)")
para("где P и X вычисляются в средней точке участка. Расход топлива на участке:")
mono("    ΔGт = (P·Cp/3600) · Δt")

h2("3.2. «Подъем» (V = const, dV/dt = 0)")
para("Скорость полета не меняется. Из первого уравнения движения при dV/dt=0:")
mono("    sinΘ = (P-X) / (m·g)")
para("Из кинематического соотношения dH/dt=V·sinΘ время прохождения участка:")
mono("    Δt = (H2-H1) / (V·sinΘ)")

h2("3.3. «Подъем-разгон» (Θ = const, dH/dV = K)")
para("Угол наклона траектории постоянен, при этом меняются и скорость, и высота "
     "линейно друг относительно друга: dH/dV=K=const, где K определяется "
     "координатами узлов сетки K=(H2-H1)/(V2-V1). Подставляя dH/dt=K·dV/dt в "
     "кинематическое соотношение и используя уравнение движения вдоль траектории, "
     "получаем:")
mono("    sinΘ = K·(P-X) / (m·(V+K·g))")
mono("    Δt = m·(V2-V1) / (P - X - m·g·sinΘ)")
para("Расход топлива для всех трех типов элементарных траекторий вычисляется "
     "одинаково: ΔGт = (P·Cp/3600)·Δt, где P - тяга в средней точке участка.")
para("Участок считается недопустимым (бесконечно большой «вес»), если "
     "избыток тяги (P-X) отрицателен, либо требуемый Cy превышает Cy_max "
     "(срыв потока).")

